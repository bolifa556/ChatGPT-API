import assert from 'node:assert/strict';
import { prepareWithRecovery, updateEnv } from '../src/gateway-recovery.mjs';
import { recoverSettings, Cancelled } from '../macos/dmg/gui.mjs';
import { requestSettings } from '../linux/settings.mjs';

const unavailable = () => Object.assign(new Error('[gateway_unavailable] HTTP 401'), { code: 'gateway_unavailable' });
let requests = 0, prompts = 0, writes = 0;
await assert.rejects(prepareWithRecovery(async () => { requests++; throw unavailable(); }, async () => { prompts++; return false; }), /401/);
assert.equal(requests, 1); assert.equal(prompts, 1);
requests = 0;
const cache = { gateway: { ready: false }, cached: true };
assert.equal(await prepareWithRecovery(async () => { requests++; return cache; }, async () => false), cache);
assert.equal(requests, 1);
requests = 0;
assert.equal(await prepareWithRecovery(async () => { if (++requests === 1) throw unavailable(); return 'new settings'; }, async () => { writes++; return true; }), 'new settings');
assert.equal(requests, 2); assert.equal(writes, 1);
await assert.rejects(prepareWithRecovery(async () => { throw new Error('Unrelated local port conflict'); }, async () => { throw new Error('Must not ask for credentials'); }), /Unrelated local port/);
const original = '# retained\nBASE_URL=https://old.invalid/v1\nAPI_KEY=old\nIMAGE_MODEL=keep\nUNRELATED=keep\n';
const updated = updateEnv(original, { BASE_URL: 'https://new.invalid/v1', API_KEY: 'literal$&=key' });
assert(updated.includes('API_KEY=literal$&=key\n')); assert(updated.includes('# retained\n')); assert(updated.includes('IMAGE_MODEL=keep\nUNRELATED=keep\n'));
assert.throws(() => updateEnv(original, { API_KEY: 'line\ninjection' }), /Invalid/);
const provider = { readSettings: () => ({ BASE_URL: 'https://old.invalid/v1', API_KEY: 'secret-kept' }), configure: async () => { writes++; } };
provider.userSettings = provider.readSettings;
writes = 0;
assert.equal(await recoverSettings({}, provider, async () => { throw new Cancelled(); }), false);
assert.equal(writes, 0);
let calls = 0;
assert.equal(await recoverSettings({}, provider, async () => { if (++calls === 2) throw new Cancelled(); return 'https://new.invalid/v1'; }), false);
assert.equal(writes, 0, 'Cancel at the Key prompt must not persist the preceding URL');
calls = 0;
assert.equal(await recoverSettings({}, provider, async () => ++calls === 1 ? 'https://new.invalid/v1' : ''), true);
assert.equal(writes, 1);
const argsSeen = [];
const values = await requestSettings(provider.readSettings(), { graphical: true, execute: async (program, args) => { argsSeen.push([program, args]); return argsSeen.length === 1 ? 'https://new.invalid/v1' : ''; } });
assert.equal(values.key, 'secret-kept'); assert(!JSON.stringify(argsSeen).includes('secret-kept'));
const noGui = await requestSettings(provider.readSettings(), { graphical: false, tty: false }); assert.equal(noGui, null);
console.log(JSON.stringify({ passed: true, checks: ['cancel preserves old settings', 'cached unavailable URL can still launch', 'one prompt per startup', 'new request only after submit', 'unrelated errors never ask for keys', 'Mac second-dialog cancellation is atomic', 'Linux masked key stays out of argv', 'unknown settings preserved'] }));
